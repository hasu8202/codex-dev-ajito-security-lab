/** 日本時間の日付を YYYY-MM-DD で返す */
export function jstDate(now: Date = new Date()): string {
  const jst = new Date(now.getTime() + 9 * 60 * 60 * 1000);
  return jst.toISOString().slice(0, 10);
}

export function promptFor(date: string): string {
  const days = Math.floor(Date.parse(`${date}T00:00:00Z`) / 86_400_000);
  return PROMPTS[((days % PROMPTS.length) + PROMPTS.length) % PROMPTS.length];
}
